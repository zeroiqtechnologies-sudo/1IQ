export function downloadBrochure(p: Project, devName: string) {
  const sm = summary(p);
  const text = [
    `${p.name} — DEMO BROCHURE (fictional project)`,
    `Developer: ${devName}`,
    `Location: ${p.address}`,
    `Configurations: ${p.configs.map((c) => `${c.label} ${c.carpetMinSqft}-${c.carpetMaxSqft} sq ft carpet, ${formatPriceRange(c.priceMin, c.priceMax)}`).join('; ')}`,
    `Price range: ${sm.priceLabel}`,
    `Possession: ${formatPossession(p.possession)}`,
    `Amenities: ${p.amenities.join(', ')}`,
    `Registration (as supplied, demo): ${p.registrationNo} — ${p.registrationAuthority}`,
    '',
    'This file is generated by the prototype. It is not a real brochure, offer or advertisement.',
  ].join('\n');
  const url = URL.createObjectURL(new Blob([text], { type: 'text/plain' }));
  const a = document.createElement('a');
  a.href = url;
  a.download = p.brochureName;
  a.click();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}

function Emi({ defaultPrice }: { defaultPrice: number }) {
  const [price, setPrice] = useState(Math.round(defaultPrice / 100));
  const [down, setDown] = useState(20);
  const [rate, setRate] = useState(8.5);
  const [years, setYears] = useState(20);
  const principal = price * (1 - down / 100);
  const r = rate / 12 / 100;
  const n = years * 12;
  const emi = r > 0 ? (principal * r * Math.pow(1 + r, n)) / (Math.pow(1 + r, n) - 1) : principal / n;
  return (
    <Card>
      <CardHeader title={<span className="inline-flex items-center gap-2"><Calculator className="h-4 w-4 text-teal-700" />EMI estimate</span>} subtitle="Illustrative only. Not a loan offer." />
      <div className="p-4 sm:p-5 grid grid-cols-2 gap-3 text-sm">
        <label className="col-span-2">Property price (₹)<Input type="number" min={0} value={price} onChange={(e) => setPrice(Number(e.target.value) || 0)} /></label>
        <label>Down payment %<Input type="number" min={0} max={90} value={down} onChange={(e) => setDown(Math.min(90, Number(e.target.value) || 0))} /></label>
        <label>Interest % p.a.<Input type="number" step="0.1" min={0} value={rate} onChange={(e) => setRate(Number(e.target.value) || 0)} /></label>
        <label className="col-span-2">Tenure (years)<Input type="number" min={1} max={30} value={years} onChange={(e) => setYears(Math.max(1, Number(e.target.value) || 1))} /></label>
        <div className="col-span-2 rounded-lg bg-teal-50 p-3">
          <p className="text-xs text-slate-600">Estimated monthly EMI</p>
          <p className="text-xl font-bold text-teal-800">{formatINR(Math.round(emi * 100))}</p>
          <p className="text-[11px] text-slate-500 mt-1">Assumes a fixed rate, monthly reducing balance, no fees, taxes or insurance, and loan = price − down payment. Actual eligibility and rates depend on your lender.</p>
        </div>
      </div>
    </Card>
  );
}

